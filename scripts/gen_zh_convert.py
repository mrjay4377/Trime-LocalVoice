#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build the compact offline Simplified/Traditional mapping used by voice input.

Source dictionaries come from OpenCC (Apache-2.0), already vendored in
``app/src/main/assets/shared/opencc``.

Every dictionary phrase is kept, but split into two groups:

* DIFF   - the phrase result differs from converting each character on its own.
           Those cover the "one simplified char to several traditional chars"
           cases (头发/頭髮, 里/裡 …). Stored as key<TAB>value.
* SHIELD - the remaining phrases. Their value is *exactly* the per-character
           conversion, so we only store the key; ChineseConverter rebuilds
           the value with the single-character table at runtime. They still have
           to be present: the longest-match scanner must not fall through to a
           short ambiguous phrase (e.g. 被发 -> 被髮 would turn 被发现 into
           被髮現 without the longer 被发现 entry).

This makes conversion byte-identical to using the full OpenCC dictionary while
roughly halving the asset size. The table ships inside the APK, so conversion
does not depend on the runtime OpenCC .ocd2 dictionaries built at deploy time.

Run from anywhere:  python3 scripts/gen_zh_convert.py
"""

import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.normpath(os.path.join(HERE, "..", "app", "src", "main", "assets"))
SRC = os.path.join(ASSETS, "shared", "opencc")
OUT = os.path.join(ASSETS, "voice", "zh_convert.txt")


def load(name):
    """key -> first value; OpenCC text dictionaries are tab separated."""
    result = {}
    with io.open(os.path.join(SRC, name), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            parts = line.rstrip("\r\n").split("\t")
            if len(parts) < 2:
                continue
            key = parts[0].strip()
            values = parts[1].split()
            if key and values:
                result[key] = values[0]
    return result


def by_char(text, chars):
    return "".join(chars.get(c, c) for c in text)


def split_dictionary(phrases, chars):
    diff, shield = {}, []
    for key, value in phrases.items():
        if by_char(key, chars) != value:
            diff[key] = value
        else:
            shield.append(key)
    return diff, shield


def split_chars(mapping):
    """Non-BMP keys (surrogate pairs) must go through the phrase matcher."""
    chars = {k: v for k, v in mapping.items() if len(k) == 1}
    phrases = {k: v for k, v in mapping.items() if len(k) > 1}
    return chars, phrases


def emit_map(out, section, mapping):
    out.write("[%s]\n" % section)
    for key in sorted(mapping):
        out.write("%s\t%s\n" % (key, mapping[key]))
    return len(mapping)


def emit_keys(out, section, keys):
    out.write("[%s]\n" % section)
    for key in sorted(set(keys)):
        out.write("%s\n" % key)
    return len(set(keys))


def main():
    s2t_chars_all = load("STCharacters.txt")
    t2s_chars_all = load("TSCharacters.txt")
    tw_chars_all = load("TWVariants.txt")
    hk_chars_all = load("HKVariants.txt")

    s2t_diff, s2t_shield = split_dictionary(load("STPhrases.txt"), s2t_chars_all)
    t2s_diff, t2s_shield = split_dictionary(load("TSPhrases.txt"), t2s_chars_all)
    # Regional variants are tiny; keep all of them as explicit mappings.
    # s2tw.json / s2hk.json apply them as a second chain after the s2t chain.
    tw_diff = load("TWVariantsPhrases.txt")
    tw_shield = []
    hk_diff = load("HKVariantsPhrases.txt")
    hk_shield = []

    s2t_chars, extra = split_chars(s2t_chars_all)
    s2t_diff.update(extra)
    t2s_chars, extra = split_chars(t2s_chars_all)
    t2s_diff.update(extra)
    tw_chars, extra = split_chars(tw_chars_all)
    tw_diff.update(extra)
    hk_chars, extra = split_chars(hk_chars_all)
    hk_diff.update(extra)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write(
            "# Offline Simplified/Traditional mapping for local voice input.\n"
            "# Generated by scripts/gen_zh_convert.py from OpenCC dictionaries\n"
            "# (https://github.com/BYVoid/OpenCC, Apache-2.0).\n"
            "# [*_DIFF]  key<TAB>value   [*_SHIELD]  key   [*_CHAR]  char<TAB>value\n"
            "# Phrases are matched longest-first; SHIELD values are rebuilt from CHAR.\n"
        )
        counts = [
            emit_map(out, "S2T_DIFF", s2t_diff),
            emit_keys(out, "S2T_SHIELD", s2t_shield),
            emit_map(out, "S2T_CHAR", s2t_chars),
            emit_map(out, "TW_DIFF", tw_diff),
            emit_keys(out, "TW_SHIELD", tw_shield),
            emit_map(out, "TW_CHAR", tw_chars),
            emit_map(out, "HK_DIFF", hk_diff),
            emit_keys(out, "HK_SHIELD", hk_shield),
            emit_map(out, "HK_CHAR", hk_chars),
            emit_map(out, "T2S_DIFF", t2s_diff),
            emit_keys(out, "T2S_SHIELD", t2s_shield),
            emit_map(out, "T2S_CHAR", t2s_chars),
        ]

    print("wrote %s (%d bytes)" % (OUT, os.path.getsize(OUT)))
    print(
        "s2t diff=%d shield=%d char=%d | tw diff=%d shield=%d char=%d | "
        "hk diff=%d shield=%d char=%d | t2s diff=%d shield=%d char=%d"
        % tuple(counts)
    )


if __name__ == "__main__":
    main()
